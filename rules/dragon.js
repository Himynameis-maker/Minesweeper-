/* 龍: 左端の1マスから右端の1マスまで、爆弾が1列ごとに「同じ行 or 上下1行ずれ」でつながる列(龍)が盤面のどこかに必ずある。
   龍以外の爆弾は自由(龍に触れていてもよい)。全体制約 dragon:true を CORE が実装(solver の [dragon] / gen の dsample / prep の dok・dpath)。
   dbl:true(隠れ龍): 本物の龍は盤面に1本だけ(隠れている)。龍の爆弾は数字に2個ぶんとして数える(龍でない爆弾は、たまたま左右につながって見えても1個ぶん)。
   数字 = 8近傍の爆弾数 + 8近傍に入る龍のマス数。solver の [dd](ddprop)が龍の道を列ごとのDPで絞り込み、gen は盤面ごとに本物の龍 L.dr を持つ。
   併用不可: groupBomb(連結成分が grp 個ずつ。龍は C 個以上つながる), noIsolate(塊が n 個以下。龍は C 個以上つながる),
            noTouch(縦横に隣り合う爆弾を禁止。龍は直進で縦横に並ぶ), rect(直線のみ・斜め不可。龍は斜めに進む),
            allConnected(論理的には両立するが、龍が全爆弾の背骨になり「外すと詰む」を満たしにくい。自前検査で 7x7 M=13/17 が4秒打ち切り・品質OK 1/3,0/3),
            liar / liar2(±1ズレの前提が「爆弾の個数」。龍で数え方が変わるので噛み合わない), colorDouble(どちらも数え方を変える。重みが重なる)。
   爆弾数: 下限は C(龍の最短長)だけ。上限は付けない(旧版は盤面の4割。爆弾が多いと龍が偶然できて飾りになり、品質未達や生成の遅さが増えるが、
   生成は品質を満たさない盤面を出さず失敗で返すので、上限なしでも変な盤面は出ない。ただし高密度では生成に失敗/時間切れが増える)。 */
reg({id:'dragon',
 name:'龍', desc:'盤面のどこかに、左端から右端まで爆弾がつながった龍が1本だけいる(1列進むごとに、まっすぐか上下に1マスずれる)。龍の爆弾は、数字に2個ぶんとして数える。',
 dragon:true, dbl:true,
 ok:c=>c.M>=c.C, // 龍は最低 C 個
 conflicts:['groupBomb','noIsolate','noTouch','rect','allConnected','liar','liar2','colorDouble']
});
